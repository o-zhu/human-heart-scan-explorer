import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {EchoModule, ECHO_PRESETS} from '../public/echo.js';
import {echoCompactLayout, mountEchoCompactWorkspace} from '../public/echo-mobile-v47.js';

if (!process.argv[2]) throw new Error('Pass the LinkeDOM esm/index.js path.');
const {parseHTML} = await import(pathToFileURL(process.argv[2]));
const {document, window} = parseHTML('<html><head></head><body><main id="echoPanel"></main><button id="outside">Outside</button></body></html>');
Object.assign(globalThis, {document, window});
Object.defineProperty(window.HTMLSelectElement.prototype, 'value', {
  configurable: true,
  get() { return this._value ?? this.querySelector('option[selected]')?.getAttribute('value') ?? ''; },
  set(value) { this._value = String(value); },
});
let focused = null;
Object.defineProperty(document, 'activeElement', {configurable: true, get: () => focused});
window.HTMLElement.prototype.focus = function () { focused = this; };
const frames = new Map();
let nextFrame = 1, layouts = 0;
window.requestAnimationFrame = callback => { const id = nextFrame++; frames.set(id, callback); return id; };
window.cancelAnimationFrame = id => frames.delete(id);
const pointer = {matches: false, addEventListener() {}, removeEventListener() {}};
window.matchMedia = query => { assert.equal(query, '(any-pointer: coarse)'); return pointer; };
window.innerWidth = 390; window.innerHeight = 844;
const flush = () => { for (const [id, callback] of [...frames]) { frames.delete(id); callback(); } };
const resize = (width, height = 900) => { window.innerWidth = width; window.innerHeight = height; window.dispatchEvent(new window.Event('resize')); flush(); };
const mount = document.getElementById('echoPanel');
mount.innerHTML = EchoModule.prototype.template.call({fineLabel: '79.4 µm'});
const find = name => mount.querySelector(`[data-echo="${name}"]`);
find('compact-navigation').getBoundingClientRect = () => ({bottom: 180});
const state = {mode: 'tte', preset: 'a4c'};
const originalNodes = [...mount.querySelectorAll('.echo-panel-toolbar,.echo-probe-options,.echo-model-details,.echo-cine-credit,.echo-cine-playback,.echo-detail-fold')];
const originalParents = originalNodes.map(node => node.parentNode);
const overlayNodes = [...mount.querySelectorAll('.echo-scene-heading,.echo-cine > .echo-section-heading,.echo-mpr-caption,.echo-cine-status-slot')];
const overlayParents = overlayNodes.map(node => node.parentNode);
const approach = mount.querySelector('.echo-approach');
const presetNav = mount.querySelector('.echo-active-view nav');
const anatomy = mount.querySelector('.echo-view-column');
const ultrasound = mount.querySelector('.echo-cine');
const player = find('cine-video');
const iframe = find('cine-embed');
player.setAttribute('src', '/media/tte-a4c.mp4');
iframe.setAttribute('src', 'https://www.youtube-nocookie.com/embed/example');
find('cine-visible-source').href = 'https://original.example/source';
find('cine-license').href = 'https://creativecommons.org/licenses/by-sa/3.0/';
let playerLoads = 0, controlChanges = 0;
player.load = () => playerLoads++;
find('anchor-anatomy').addEventListener('click', () => controlChanges++);
let ui;
const select = id => { const preset = ECHO_PRESETS.find(p => p.id === id); state.mode = preset.mode; state.preset = id; ui.selectionChanged(); };
ui = mountEchoCompactWorkspace({mount, presets: ECHO_PRESETS, getState: () => state, onSelect: select, onLayout: () => layouts++, view: window});

assert.deepEqual(echoCompactLayout({width: 1300, height: 1000}), {compact: false, phone: false});
assert.deepEqual(echoCompactLayout({width: 1300, height: 740}), {compact: true, phone: false});
assert.deepEqual(echoCompactLayout({width: 1366, height: 1024, coarse: true}), {compact: true, phone: false});
assert.equal(mount.dataset.echoVisiblePane, 'anatomy');
assert.equal(anatomy.hidden, false);
assert.equal(ultrasound.hidden, true);
assert.equal(mount.querySelector('.echo-library').hidden, true);
assert.equal(find('compact-settings').hidden, true);
assert.equal(find('compact-view').querySelectorAll('option').length, 28);
assert.equal(find('compact-view').value, 'a4c');
assert.equal(find('compact-approach').firstElementChild, approach);
assert.equal(find('compact-library-actions').firstElementChild, presetNav);
assert.ok(overlayNodes.every(node => node.parentElement.matches('.echo-comparison-screen')), 'compact headings/status use the existing visual boxes');
assert.ok(mount.querySelector('.echo-model-details-body').contains(find('ct-correspondence')));
assert.ok(mount.querySelector('.echo-model-details-body').contains(find('resolution')), 'resolution diagnostics stay in optional Model Details');
assert.ok(mount.querySelector('.echo-cine-credit-body').contains(find('cine-match')), 'reference-match diagnostics stay in optional Source Details');
assert.ok(mount.querySelector('.echo-cine-screen .echo-reference-qualifier').textContent.includes('Independent'), 'the clinical recording remains identified as independent');
assert.ok(originalNodes.every(node => find('compact-settings').contains(node)));
assert.ok(find('compact-settings').contains(find('context-caption')));
assert.ok(find('compact-settings').contains(find('probe-fit-note')));
assert.equal(find('context-alert').parentNode, anatomy, 'critical anatomy failure/pose alerts stay with the visible pane');
assert.equal(mount.querySelectorAll('[data-mode]').length, 2);
assert.equal(mount.querySelectorAll('#echoCineSelect').length, 1);
assert.ok(mount.style.getPropertyValue('--echo-compact-menu-height').endsWith('px'));

find('compact-browse').click();
assert.equal(mount.querySelector('.echo-library').hidden, false);
assert.equal(find('compact-browse').getAttribute('aria-expanded'), 'true');
assert.equal(document.activeElement, find('search'));
find('compact-settings-toggle').click();
assert.equal(mount.querySelector('.echo-library').hidden, true);
assert.equal(find('compact-settings').hidden, false);
assert.equal(find('compact-settings-toggle').getAttribute('aria-expanded'), 'true');
assert.equal(document.activeElement, find('compact-settings-close'));
find('anchor-anatomy').click();
assert.equal(controlChanges, 1, 'moved controls retain their existing listener');
const escape = new window.Event('keydown', {bubbles: true, cancelable: true});
escape.key = 'Escape';
document.dispatchEvent(escape);
assert.equal(find('compact-settings').hidden, true);
assert.equal(document.activeElement, find('compact-settings-toggle'));
find('compact-browse').click();
document.getElementById('outside').dispatchEvent(new window.Event('pointerdown', {bubbles: true}));
assert.equal(mount.querySelector('.echo-library').hidden, true, 'outside pointer dismisses the library');

find('compact-browse').click();
find('compact-view').value = 'plax';
find('compact-view').dispatchEvent(new window.Event('change'));
assert.equal(state.preset, 'plax');
assert.equal(mount.querySelector('.echo-library').hidden, true);
assert.equal(document.activeElement, find('compact-view'));
select('me4c');
assert.equal(find('compact-view').querySelectorAll('option').length, 28);
assert.equal(find('compact-view').getAttribute('aria-label'), 'TEE Reference View');
assert.equal(find('compact-view').value, 'me4c');
assert.ok([...find('compact-view').querySelectorAll('option')].every(option => ECHO_PRESETS.some(p => p.mode === 'tee' && p.id === option.value)));

// Default changes with the available space until the user makes an explicit choice.
resize(834, 1194);
assert.equal(mount.dataset.echoVisiblePane, 'both');
assert.equal(anatomy.hidden, false);
assert.equal(ultrasound.hidden, false);
resize(820, 1180);
assert.equal(mount.dataset.echoVisiblePane, 'both', 'portrait tablets retain the paired default when CSS stacks the images');
assert.equal(mount.classList.contains('echo-phone'), false, 'portrait tablet stacking must not activate the two-row phone navigation');
assert.equal(find('compact-navigation').hidden, false);
resize(390, 844);
assert.equal(mount.dataset.echoVisiblePane, 'anatomy');
mount.querySelector('[data-echo-pane="ultrasound"]').click();
assert.equal(mount.dataset.echoVisiblePane, 'ultrasound');
assert.equal(anatomy.hidden, true);
assert.equal(ultrasound.hidden, false);
resize(834, 1194);
assert.equal(mount.dataset.echoVisiblePane, 'ultrasound', 'explicit pane choice survives tablet resize');
resize(1400, 1000);
assert.equal(ui.compact, false);
assert.equal(mount.dataset.echoVisiblePane, 'both');
assert.equal(find('compact-navigation').hidden, true);
assert.equal(mount.querySelector('.echo-library').hidden, false);
assert.ok(originalNodes.every((node, index) => node.parentNode === originalParents[index]));
assert.ok(overlayNodes.every((node, index) => node.parentNode === overlayParents[index]), 'desktop restores the original heading and status nodes');
assert.equal(approach.parentElement, mount.querySelector('.echo-library'));
assert.equal(presetNav.parentElement, mount.querySelector('.echo-active-view'));
assert.ok(mount.querySelector('.echo-model-details-body').contains(find('ct-correspondence')), 'diagnostics stay out of the main comparison at every width');
resize(1366, 740);
assert.equal(ui.compact, true);
assert.equal(mount.dataset.echoVisiblePane, 'ultrasound');
resize(1366, 1024);
assert.equal(ui.compact, false);
pointer.matches = true;
resize(1366, 1024);
assert.equal(ui.compact, true, 'large touch-capable iPads with a trackpad also receive compact controls');
assert.equal(find('cine-video'), player);
assert.equal(find('cine-embed'), iframe);
assert.equal(player.getAttribute('src'), '/media/tte-a4c.mp4');
assert.equal(iframe.getAttribute('src'), 'https://www.youtube-nocookie.com/embed/example');
assert.equal(playerLoads, 0, 'presentation changes never reload media');
assert.equal(find('cine-visible-source').href, 'https://original.example/source');
assert.equal(find('cine-license').href, 'https://creativecommons.org/licenses/by-sa/3.0/');
assert.equal(mount.querySelectorAll('#echoCineSelect').length, 1);
assert.equal(mount.querySelector('.echo-cine-status-slot').parentNode, ultrasound.querySelector('.echo-comparison-screen'));
find('compact-settings-toggle').click();
ui.close();
assert.equal(find('compact-settings').hidden, true, 'leaving the workspace closes its controls');
ui.destroy();
assert.ok(originalNodes.every((node, index) => node.parentNode === originalParents[index]));
assert.ok(overlayNodes.every((node, index) => node.parentNode === overlayParents[index]));
assert.equal(anatomy.hidden, false);
assert.equal(ultrasound.hidden, false);
const priorLayouts = layouts;
resize(390, 844);
assert.equal(layouts, priorLayouts, 'destroy removes the responsive listener');
console.log('PASS compact Echo: phone/tablet/short/coarse layouts, in-screen headings/status with exact desktop restoration, optional quality diagnostics, independent recording qualifier, explicit pane preference, single live controls, native view selection, dismissible search/settings, focus return, source/player continuity and teardown.');
